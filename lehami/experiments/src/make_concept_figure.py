#!/usr/bin/env python
"""Paper Figure 1: the idea, in one picture.

Bottom, the observation space: real rendered frames from `pendulum.h5`. Consecutive frames
share almost no support in pixel coordinates, and one frame does not determine how fast the
system is moving.

Top left, the latent representation space: the model's own coordinates, split into a
canonical pair (q, p), where the transition is generated by a learned scalar H_phi and
integrated by a symplectic step. The level sets and the trajectory are integrated with the
same leapfrog composition the model uses.

Top right, what symplecticity buys along a rollout: a cloud of nearby latent states carried
by that same step. It shears, and its area does not change. The areas printed are measured
from the transported polygon with the shoelace formula, not asserted; the boundary is
sampled finely enough that the polygon area tracks the true area to better than 0.1 percent
over the interval shown.

The top row is schematic in one respect the caption states: the trained latent is
2d-dimensional and this is a two-dimensional cartoon of it, drawn with the pendulum
Hamiltonian because it is legible, not because it is what the model learns.

    .venv/bin/python lehami/experiments/src/make_concept_figure.py

Writes submission/figs/diagrams/concept_hjepa.pdf (+ .png).
"""
from __future__ import annotations

from pathlib import Path

import h5py
import hdf5plugin  # noqa: F401 -- registers the blosc filter the dataset was written with
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.patches import Polygon

ROOT = Path(__file__).resolve().parents[3]
OUT_DIR = ROOT / "submission" / "figs" / "diagrams"
H5 = Path.home() / ".stable_worldmodel" / "pendulum.h5"

INK, MUTED, FAINT = "#0b0b0b", "#5b5b57", "#9aa1ab"
BLUE, WARM = "#2a78d6", "#eb6834"
LATENT_BG = "#f5f8fc"


def dK(p):
    return p


def dV(q):
    return np.sin(q)


def leapfrog(q, p, h, n):
    """The symmetric composition the model integrates with, in two dimensions."""
    qs, ps = [q.copy()], [p.copy()]
    for _ in range(n):
        p = p - 0.5 * h * dV(q)
        q = q + h * dK(p)
        p = p - 0.5 * h * dV(q)
        qs.append(q.copy())
        ps.append(p.copy())
    return np.array(qs), np.array(ps)


def polygon_area(x, y):
    """Shoelace, so the area in the figure is measured and not asserted."""
    return 0.5 * abs(np.dot(x, np.roll(y, -1)) - np.dot(y, np.roll(x, -1)))


def main():
    n_frames = 5
    with h5py.File(H5, "r") as f:
        off, ln = int(f["ep_offset"][0]), int(f["ep_len"][0])
        stride = max(1, ln // 26)
        frames = [f["pixels"][off + i * stride] for i in range(n_frames)]

    fig = plt.figure(figsize=(10.0, 4.6))
    ax = fig.add_axes([0.055, 0.40, 0.60, 0.55])
    axb = fig.add_axes([0.715, 0.40, 0.24, 0.55])
    for a in (ax, axb):
        a.set_facecolor(LATENT_BG)
        a.set(xticks=[], yticks=[])
        for sp in a.spines.values():
            sp.set_color("#c9cdd4")

    # ── main panel: level sets of the generator and one trajectory ───────────
    qq, pp = np.meshgrid(np.linspace(-3.0, 3.0, 400), np.linspace(-2.3, 2.3, 400))
    ax.contour(qq, pp, 0.5 * pp ** 2 + (1 - np.cos(qq)),
               levels=np.linspace(0.2, 3.0, 9), colors=MUTED, linewidths=0.6, alpha=0.40)

    qs, ps = leapfrog(np.array([-2.2]), np.array([0.0]), 0.02, 1400)
    qs, ps = qs[:, 0], ps[:, 0]
    ax.plot(qs, ps, color=BLUE, lw=2.0, zorder=3, solid_capstyle="round")
    # The five states shown below: the upper branch, where q sweeps left to right, so the
    # frames beneath can be placed under their own latent state and the arrows stay short.
    up = np.where(ps > 0.15)[0]
    seg = up[(qs[up] > -1.85) & (qs[up] < 1.85)]
    # Evenly spaced in q rather than in time: the orbit is fastest at the bottom of the
    # potential, so equal time steps would bunch the marks near the turning points and
    # the frames below them would collide.
    targets = np.linspace(-1.9, 1.9, n_frames)
    marks = np.array([seg[np.argmin(np.abs(qs[seg] - t))] for t in targets])
    ax.scatter(qs[marks], ps[marks], s=44, color=BLUE, zorder=5,
               edgecolor="white", linewidth=1.1)
    ax.annotate("", xy=(qs[marks[-1]] + 0.55, ps[marks[-1]] - 0.12),
                xytext=(qs[marks[-1]] + 0.05, ps[marks[-1]] + 0.02),
                arrowprops=dict(arrowstyle="-|>", color=BLUE, lw=1.6))

    ax.set_title("latent representation space $(\\mathbf{q}, \\mathbf{p})$",
                 loc="left", fontsize=10, color=INK, pad=6)
    ax.text(0.015, 0.965, "the transition is generated by a learned $H_\\phi$\nand taken "
            "by a symplectic step", transform=ax.transAxes, va="top", fontsize=8.4,
            color=MUTED)
    ax.text(0.985, 0.04, "level sets of $H_\\phi$", transform=ax.transAxes,
            ha="right", fontsize=8, color=MUTED)
    ax.set_xlabel("$\\mathbf{q}$, the position-like block", fontsize=9, labelpad=2)
    ax.set_ylabel("$\\mathbf{p}$, the momentum-like block", fontsize=9)
    ax.set(xlim=(-3.0, 3.0), ylim=(-1.95, 1.95))

    # ── right panel: a cloud of nearby states, transported by the same step ──
    th = np.linspace(0, 2 * np.pi, 2000, endpoint=False)
    cq, cp = 0.32 * np.cos(th) - 0.9, 0.26 * np.sin(th) + 1.05
    snaps = [0, 55, 110]
    bq, bp = leapfrog(cq, cp, 0.02, max(snaps))
    areas = [polygon_area(bq[s], bp[s]) for s in snaps]
    for j, s in enumerate(snaps):
        axb.add_patch(Polygon(np.column_stack([bq[s], bp[s]]), closed=True,
                              facecolor=WARM, edgecolor=WARM, alpha=0.55 - 0.12 * j,
                              lw=1.1, zorder=4))
    axb.annotate("", xy=(bq[snaps[-1]].mean() - 0.28, bp[snaps[-1]].mean() + 0.30),
                 xytext=(bq[0].mean() + 0.22, bp[0].mean() + 0.34),
                 arrowprops=dict(arrowstyle="-|>", color=WARM, lw=1.2,
                                 connectionstyle="arc3,rad=-0.25"))
    axb.set_title("the same step, on a cloud of states", loc="left", fontsize=10,
                  color=INK, pad=6)
    axb.text(0.5, 0.10, "it shears, and its volume\nis unchanged: "
             f"area {areas[0]:.3f} to {areas[-1]:.3f}",
             transform=axb.transAxes, ha="center", va="bottom", fontsize=8.0, color=WARM)
    pad = 0.55
    axb.set(xlim=(bq[:max(snaps) + 1].min() - pad, bq[:max(snaps) + 1].max() + pad),
            ylim=(bp[:max(snaps) + 1].min() - pad, bp[:max(snaps) + 1].max() + 0.9))

    # ── the observation row, placed under the latent state it encodes ────────
    w = 0.088
    for i, (img, m) in enumerate(zip(frames, marks)):
        xf = ax.transData.transform((qs[m], ps[m]))[0] / fig.get_size_inches()[0] \
            / fig.dpi
        left = min(max(xf - w / 2, 0.01), 0.66 - w)
        axi = fig.add_axes([left, 0.06, w, w * 10.0 / 4.6])
        axi.imshow(img)
        axi.set(xticks=[], yticks=[])
        axi.grid(False)
        for sp in axi.spines.values():
            sp.set_color("#c9cdd4")
        axi.set_xlabel(f"$x_{{t+{i * 4}}}$", fontsize=8.5, labelpad=2)
        ax.annotate("", xy=(qs[m], ps[m]), xycoords=ax.transData,
                    xytext=(left + w / 2, 0.06 + w * 10.0 / 4.6), textcoords="figure fraction",
                    arrowprops=dict(arrowstyle="-|>", color=FAINT, lw=1.0,
                                    shrinkA=1, shrinkB=5))
    fig.text(0.055, 0.335, "observation space: rendered frames. Consecutive frames share "
             "almost no pixels, and one frame does not determine the velocity.",
             fontsize=8.4, color=MUTED)
    fig.text(0.075, 0.255, "encoder", fontsize=8.4, color=FAINT, rotation=90,
             ha="center", va="center")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for ext in ("pdf", "png"):
        p = OUT_DIR / f"concept_hjepa.{ext}"
        fig.savefig(p, dpi=200, bbox_inches="tight")
        print(f"wrote {p}")
    print("transported cloud areas:", [f"{a:.6f}" for a in areas],
          f"  max relative drift {max(abs(a / areas[0] - 1) for a in areas):.2e}")


if __name__ == "__main__":
    main()
