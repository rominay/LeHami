#!/usr/bin/env python
"""Paper Figure 1, extended: the idea plus the two capabilities an unconstrained map lacks.

Same picture as `make_concept_figure.py` -- observation frames at the bottom, the latent
canonical pair (q, p) above them, the transition generated by a learned scalar and taken by
a symplectic step -- with the right-hand column now carrying three properties of that step
rather than one:

  (i)   VOLUME.  A cloud of nearby latent states carried by the step shears and keeps its
        area.  Both areas are measured from the transported polygon with the shoelace
        formula, not asserted.

  (ii)  STEP SIZE.  h is an argument to the integrator, not a property of the weights, so
        the same H_phi places states BETWEEN observed frames.  The panel integrates the
        same interval at h and at h/4 and the fine states land on the same arc.  The two
        cannot agree exactly -- each h carries its own modified Hamiltonian -- so the
        endpoint gap is printed to STDOUT rather than onto the figure, where a bare
        percentage would read as a defect instead of as the discretisation it is.

  (iii) TIME REVERSAL.  Run K steps, negate p, run K steps again.  Negating p and stepping
        forward is the SAME map as stepping backward in time (h -> -h): p -> -p conjugates
        the leapfrog into its own inverse, which is why the panel labels the return leg
        with both.  For a kinetic term even
        in p the leapfrog composition is exactly reversible, so q returns to where it
        started; the closure is measured and printed to stdout, not onto the figure.  Evenness is the hypothesis, which is
        the point: reversibility is a testable property of what was learned, not an
        assumption.  (K(p) = p^2/2 here is even, so the toy closes at machine precision.
        The TRAINED model's measured round trip is the results figure,
        submission/figs/cons_pendulum/dt_and_reversal.pdf, panel (b).)

The top row is schematic in the one respect the caption must state: the trained latent is
2d-dimensional and this is a two-dimensional cartoon of it, drawn with the pendulum
Hamiltonian because it is legible, not because it is what the model learns.  Every number
printed on the figure is computed by this script from the composition it draws.

    .venv/bin/python lehami/experiments/src/make_concept_properties_figure.py

Writes submission/figs/diagrams/concept_lehami_properties.pdf (+ .png).
"""
from __future__ import annotations

from pathlib import Path

import h5py
import hdf5plugin  # noqa: F401 -- registers the blosc filter the dataset was written with
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.patches import Polygon

ROOT = Path(__file__).resolve().parents[3]
OUT_DIR = ROOT / "submission" / "figs" / "diagrams"
H5 = Path.home() / ".stable_worldmodel" / "pendulum.h5"

INK, MUTED, FAINT = "#0b0b0b", "#5b5b57", "#9aa1ab"
BLUE, WARM, TEAL = "#2a78d6", "#eb6834", "#1a9e8f"
# The return leg in (iii) sits ON the blue outbound curve, so it needs a colour
# that separates from blue at 1.7pt, not just from the background: a deep
# magenta reads at small size and stays distinct in greyscale and for the common
# colour-vision deficiencies.  The orange WARM is kept for (i), where it is a
# large filled shape on a pale field and legibility was never the issue.
REV = "#c2185b"
LATENT_BG = "#f5f8fc"


def dK(p):
    """K(p) = p^2/2 -- EVEN in p, which is what makes the leapfrog exactly reversible."""
    return p


def dV(q):
    return np.sin(q)


def leapfrog(q, p, h, n):
    """The symmetric composition the model integrates with, in two dimensions."""
    qs, ps = [q.copy()], [p.copy()]
    for _ in range(n):
        p = p - 0.5 * h * dV(q)
        q = q + h * dK(p)
        p = p - 0.5 * h * dV(q)
        qs.append(q.copy())
        ps.append(p.copy())
    return np.array(qs), np.array(ps)


def polygon_area(x, y):
    """Shoelace, so the area in the figure is measured and not asserted."""
    return 0.5 * abs(np.dot(x, np.roll(y, -1)) - np.dot(y, np.roll(x, -1)))


def _style(a):
    a.set_facecolor(LATENT_BG)
    a.set(xticks=[], yticks=[])
    for sp in a.spines.values():
        sp.set_color("#c9cdd4")


def main():
    n_frames = 5
    with h5py.File(H5, "r") as f:
        off, ln = int(f["ep_offset"][0]), int(f["ep_len"][0])
        stride = max(1, ln // 26)
        frames = [f["pixels"][off + i * stride] for i in range(n_frames)]

    fig = plt.figure(figsize=(11.6, 6.0))
    ax = fig.add_axes([0.050, 0.430, 0.545, 0.525])          # latent space
    ax_vol = fig.add_axes([0.665, 0.665, 0.315, 0.290])      # (i)   volume
    ax_dt = fig.add_axes([0.665, 0.375, 0.315, 0.215])       # (ii)  step size
    ax_rev = fig.add_axes([0.665, 0.065, 0.315, 0.215])      # (iii) reversal
    for a in (ax, ax_vol, ax_dt, ax_rev):
        _style(a)

    # ── main panel: level sets of the generator and one trajectory ───────────
    qq, pp = np.meshgrid(np.linspace(-3.0, 3.0, 400), np.linspace(-2.3, 2.3, 400))
    ax.contour(qq, pp, 0.5 * pp ** 2 + (1 - np.cos(qq)),
               levels=np.linspace(0.2, 3.0, 9), colors=MUTED, linewidths=0.6, alpha=0.40)

    qs, ps = leapfrog(np.array([-2.2]), np.array([0.0]), 0.02, 1400)
    qs, ps = qs[:, 0], ps[:, 0]
    ax.plot(qs, ps, color=BLUE, lw=2.0, zorder=3, solid_capstyle="round")
    up = np.where(ps > 0.15)[0]
    seg = up[(qs[up] > -1.85) & (qs[up] < 1.85)]
    targets = np.linspace(-1.9, 1.9, n_frames)
    marks = np.array([seg[np.argmin(np.abs(qs[seg] - t))] for t in targets])
    ax.scatter(qs[marks], ps[marks], s=44, color=BLUE, zorder=5,
               edgecolor="white", linewidth=1.1)
    # Direction of travel, drawn along the curve itself between two of its own samples.
    tip = marks[-1] + 60
    ax.annotate("", xy=(qs[tip], ps[tip]), xytext=(qs[tip - 22], ps[tip - 22]),
                arrowprops=dict(arrowstyle="-|>", color=BLUE, lw=2.2, shrinkA=0,
                                shrinkB=0, mutation_scale=22), zorder=6)
    ax.annotate("direction of the rollout", xy=(qs[tip], ps[tip]), xytext=(-2, -16),
                textcoords="offset points", ha="right", va="top", fontsize=9.0,
                color=BLUE, zorder=10,
                bbox=dict(fc=LATENT_BG, ec="none", pad=1.6))

    ax.set_title("latent representation space $(\\mathbf{q}, \\mathbf{p})$",
                 loc="left", fontsize=11.5, color=INK, pad=6)
    ax.text(0.015, 0.965, "the transition is generated by a learned $H_\\phi$\nand taken "
            "by a symplectic step", transform=ax.transAxes, va="top", fontsize=9.6,
            color=INK, zorder=10, bbox=dict(fc=LATENT_BG, ec="none", pad=1.6))
    ax.text(0.985, 0.04, "level sets of $H_\\phi$", transform=ax.transAxes,
            ha="right", fontsize=9.2, color=INK, zorder=10, bbox=dict(fc=LATENT_BG, ec="none", pad=1.6))
    ax.set_xlabel("$\\mathbf{q}$, the position-like block", fontsize=10.2, labelpad=2)
    ax.set_ylabel("$\\mathbf{p}$, the momentum-like block", fontsize=10.2)
    ax.set(xlim=(-3.0, 3.0), ylim=(-1.95, 1.95))

    # ── (i) a cloud of nearby states, transported by the same step ───────────
    th = np.linspace(0, 2 * np.pi, 2000, endpoint=False)
    cq, cp = 0.32 * np.cos(th) - 0.9, 0.26 * np.sin(th) + 1.05
    snaps = [0, 55, 110]
    bq, bp = leapfrog(cq, cp, 0.02, max(snaps))
    areas = [polygon_area(bq[s], bp[s]) for s in snaps]
    for j, s in enumerate(snaps):
        ax_vol.add_patch(Polygon(np.column_stack([bq[s], bp[s]]), closed=True,
                                 facecolor=WARM, edgecolor=WARM, alpha=0.55 - 0.12 * j,
                                 lw=1.1, zorder=4))
    ax_vol.annotate("", xy=(bq[snaps[-1]].mean() - 0.26, bp[snaps[-1]].mean() + 0.28),
                    xytext=(bq[0].mean() + 0.20, bp[0].mean() + 0.32),
                    arrowprops=dict(arrowstyle="-|>", color=WARM, lw=1.2,
                                    connectionstyle="arc3,rad=-0.25"))
    ax_vol.set_title("(i)  it shears, and its volume does not change",
                     loc="left", fontsize=10.4, color=INK, pad=5)
    ax_vol.text(0.5, 0.055, f"area {areas[0]:.3f} $\\rightarrow$ {areas[-1]:.3f}",
                transform=ax_vol.transAxes, ha="center", va="bottom",
                fontsize=9.2, color=WARM)
    # Equal DATA scaling, set by hand rather than through set_aspect: the "datalim"
    # adjustment discards the y limits given to it, which cropped the third cloud.  Fit a
    # box around every drawn snapshot, pad it, then widen the shorter axis until the data
    # aspect matches the panel's own aspect -- so the shear is undistorted AND nothing is cut.
    vis = slice(0, max(snaps) + 1)
    x0, x1 = bq[vis].min(), bq[vis].max()
    y0, y1 = bp[vis].min(), bp[vis].max()
    pad = 0.14
    x0, x1, y0, y1 = x0 - pad, x1 + pad, y0 - pad, y1 + pad
    bx, by, bw, bh = ax_vol.get_position().bounds
    box_aspect = (bw * fig.get_size_inches()[0]) / (bh * fig.get_size_inches()[1])
    xr, yr = x1 - x0, y1 - y0
    if xr / yr < box_aspect:                      # too narrow: widen x about its centre
        grow = (yr * box_aspect - xr) / 2
        x0, x1 = x0 - grow, x1 + grow
    else:                                         # too wide: raise y about its centre
        grow = (xr / box_aspect - yr) / 2
        y0, y1 = y0 - grow, y1 + grow
    ax_vol.set(xlim=(x0, x1), ylim=(y0, y1))

    # ── (ii) the step size is an argument, not a property of the weights ─────
    # One "frame" is h; the same generator integrated at h/4 puts states between frames.
    h_frame, n_frame = 0.25, 4
    z0 = (np.array([-1.55]), np.array([0.95]))
    cq_h, cp_h = leapfrog(*z0, h_frame, n_frame)
    cq_q, cp_q = leapfrog(*z0, h_frame / 4, 4 * n_frame)
    endpoint_gap = float(np.hypot(cq_h[-1, 0] - cq_q[-1, 0], cp_h[-1, 0] - cp_q[-1, 0]))
    # Quoted against the length of one frame's displacement: an absolute gap in latent
    # units means nothing to a reader, and the honest claim is that the two agree to a
    # small fraction of a step, not that they are identical (they cannot be -- each h
    # carries its own modified Hamiltonian).
    frame_len = float(np.hypot(cq_h[1, 0] - cq_h[0, 0], cp_h[1, 0] - cp_h[0, 0]))

    ax_dt.plot(cq_q[:, 0], cp_q[:, 0], color=BLUE, lw=1.4, alpha=0.45, zorder=2)
    ax_dt.scatter(cq_q[1:-1, 0], cp_q[1:-1, 0], s=9, color=BLUE, alpha=0.75, zorder=3,
                  label="$h/4$: states between frames")
    ax_dt.scatter(cq_h[:, 0], cp_h[:, 0], s=46, color=BLUE, zorder=5,
                  edgecolor="white", linewidth=1.1, label="$h$: the observed frames")
    ax_dt.set_title("(ii)  the step size is an argument to the integrator",
                    loc="left", fontsize=10.4, color=INK, pad=5)
    ax_dt.legend(loc="lower center", fontsize=8.4, frameon=False, handletextpad=0.35,
                 borderpad=0.2, labelspacing=0.25, bbox_to_anchor=(0.52, -0.02))
    ax_dt.text(0.015, 0.93, "the same $H_\\phi$, two step sizes",
               transform=ax_dt.transAxes, va="top", fontsize=8.8, color=INK, zorder=10)
    ax_dt.set_xlabel("$\\mathbf{q}$", fontsize=9.6, labelpad=1)
    ax_dt.set_ylabel("$\\mathbf{p}$", fontsize=9.6, labelpad=1)

    # ── (iii) reversal: K steps out, p -> -p, K steps back ───────────────────
    # Chosen so the forward leg does not cross the turning point: the out-and-back then
    # reads as a symmetric tent rather than as an orbit that happened to come back.
    K, h_rev = 12, 0.20
    r0 = (np.array([-2.40]), np.array([0.70]))
    fq, fp = leapfrog(*r0, h_rev, K)
    rq, rp = leapfrog(fq[-1], -fp[-1], h_rev, K)          # the momentum flip
    closure = float(max(abs(rq[-1, 0] - r0[0][0]), abs(-rp[-1, 0] - r0[1][0])))

    # The x axis is TIME, not cumulative step count.  On a cumulative axis the return leg
    # advances left to right, which draws a tent and points the "backward" arrow the wrong
    # way; against time the return runs right to left and lands ON the outbound curve,
    # which is the actual content of reversibility -- the path is retraced, not merely
    # revisited at its endpoint.
    kk = np.arange(K + 1)
    # The two legs coincide exactly, so they are drawn to be read through each other:
    # a wide blue solid underneath, a narrow orange dash on top with gaps wider than the
    # dashes, so blue shows between every stroke.  No y offset -- separating them would
    # misrepresent the one thing the panel is claiming, that the path is retraced.
    ax_rev.plot(kk, fq[:, 0], color=BLUE, lw=3.4, zorder=3, solid_capstyle="round")
    ax_rev.plot(kk[::-1], rq[:, 0], color=REV, lw=2.0, ls=(0, (2.6, 4.6)), zorder=4,
                dash_capstyle="round")
    ax_rev.scatter([0, K], [fq[0, 0], fq[-1, 0]], s=42, zorder=6,
                   color=[BLUE, MUTED], edgecolor="white", linewidth=1.1)
    ax_rev.axhline(r0[0][0], color=FAINT, lw=0.8, ls=":", zorder=1)
    lo, hi = fq[:, 0].min(), fq[:, 0].max()
    ax_rev.set_ylim(lo - 0.16 * (hi - lo), hi + 0.14 * (hi - lo))
    ax_rev.set_title("(iii)  the same step runs backwards as well as forwards",
                     loc="left", fontsize=10.4, color=INK, pad=5)

    # Direction arrows ON the two legs, so "out" and "back" are read off the picture
    # rather than off a legend.  Negating p and stepping forward IS stepping backward in
    # time: p -> -p conjugates the leapfrog into its own inverse, which is the h -> -h map.
    # Both arrows sit on the one shared curve, at different points along it so neither
    # hides the other: forward points right, backward points LEFT, down the same path.
    a, b = int(0.14 * K), int(0.40 * K)
    c, d = int(0.86 * K), int(0.60 * K)
    ax_rev.annotate("", xy=(b, fq[b, 0]), xytext=(a, fq[a, 0]),
                    arrowprops=dict(arrowstyle="-|>", color=BLUE, lw=1.8, shrinkA=0,
                                    shrinkB=0))
    ax_rev.annotate("", xy=(d, fq[d, 0]), xytext=(c, fq[c, 0]),
                    arrowprops=dict(arrowstyle="-|>", color=REV, lw=1.9, shrinkA=0,
                                    shrinkB=0))
    ax_rev.annotate("forward", xy=((a + b) / 2, fq[(a + b) // 2, 0]),
                    xytext=(-3, 9), textcoords="offset points", ha="right", va="bottom",
                    fontsize=9.0, color=BLUE)
    # Upper right is the empty wedge above the descending return leg; anchoring the label
    # there keeps it clear of both the arrow and the panel edge.
    ax_rev.annotate("backward, $t \\rightarrow -t$",
                    xy=((c + d) / 2, fq[(c + d) // 2, 0]),
                    xytext=(4, -9), textcoords="offset points", ha="left", va="top",
                    fontsize=9.0, color=REV)
    ax_rev.set_xlabel("time, in steps", fontsize=9.6, labelpad=1)
    ax_rev.set_ylabel("$\\mathbf{q}$", fontsize=9.6, labelpad=1)

    # ── the observation row, placed under the latent state it encodes ────────
    w = 0.086
    for i, (img, m) in enumerate(zip(frames, marks)):
        xf = ax.transData.transform((qs[m], ps[m]))[0] / fig.get_size_inches()[0] \
            / fig.dpi
        left = min(max(xf - w / 2, 0.01), 0.60 - w)
        axi = fig.add_axes([left, 0.095, w, w * 11.6 / 6.0])
        axi.imshow(img)
        axi.set(xticks=[], yticks=[])
        axi.grid(False)
        for sp in axi.spines.values():
            sp.set_color("#c9cdd4")
        axi.set_xlabel(f"$x_{{t+{i * 4}}}$", fontsize=9.6, labelpad=2)
        y_bot = 0.095 + w * 11.6 / 6.0
        ax.annotate("", xy=(qs[m], ps[m]), xycoords=ax.transData,
                    xytext=(left + w / 2, y_bot), textcoords="figure fraction",
                    arrowprops=dict(arrowstyle="-|>", color=FAINT, lw=1.2,
                                    linestyle=(0, (1.4, 2.2)), shrinkA=1, shrinkB=5))
        # One "encoder" per frame, sitting ON its own arrow: the map is per-frame, and a
        # single label on the bundle read as though one encoder consumed all five at once.
        # Placed by interpolating each arrow to a common height, so they line up in a row.
        x_top, y_top = fig.transFigure.inverted().transform(
            ax.transData.transform((qs[m], ps[m])))
        y_lab = 0.335
        t = (y_lab - y_bot) / (y_top - y_bot)
        fig.text(left + w / 2 + t * (x_top - (left + w / 2)), y_lab, "encoder",
                 ha="center", va="center", fontsize=8.6, color=INK,
                 bbox=dict(boxstyle="round,pad=0.30", fc="white", ec="#c9cdd4", lw=0.7))
    fig.text(0.050, 0.018, "observation space: rendered frames. Consecutive frames share "
             "almost no pixels, and one frame does not determine the velocity.",
             fontsize=9.6, color=INK)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for ext in ("pdf", "png"):
        p = OUT_DIR / f"concept_lehami_properties.{ext}"
        fig.savefig(p, dpi=200, bbox_inches="tight")
        print(f"wrote {p}")
    print("transported cloud areas:", [f"{a:.6f}" for a in areas],
          f"  max relative drift {max(abs(a / areas[0] - 1) for a in areas):.2e}")
    print(f"step-size panel: h={h_frame}, endpoint gap h vs h/4 = {endpoint_gap:.3e} "
          f"({endpoint_gap / frame_len:.2%} of one frame)")
    print(f"reversal panel:  K={K}, h={h_rev}, round-trip closure = {closure:.3e}")


if __name__ == "__main__":
    main()
