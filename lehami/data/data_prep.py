"""Data preparation: inspect an HDF5 dataset, compute a reproducible train/test split,
and persist a JSON manifest that is sufficient to reconstruct the split exactly.

The data itself is never written — only the manifest.

Three split methods are supported (select with --split-method):

  episode (default)
      Shuffle episodes and assign whole episodes to train or test.
      Guarantees no data leakage at episode boundaries.
      Manifest stores the exact train/test episode index lists.
      Default ratio: 0.75.

  clip
      Matches the behaviour of the existing train.py: HDF5Dataset produces
      overlapping windows of `num_steps` consecutive frames (clips); the clip
      list is shuffled and split.  No episode-boundary guarantee.
      Manifest stores the parameters (num_steps, frameskip, seed, ratio)
      needed to reproduce the split exactly with spt.data.random_split.
      Default ratio: 0.90.

  episode_srnn
      Episode-level split (no leakage) with truncated training trajectories,
      following the protocol in Chen et al. ICLR 2020 (SRNN):
        - Episodes are shuffled and split at the episode level (default ratio: 0.90).
        - Training clips are sampled only from the first `train_frames` frames of
          each training episode, so the model is trained on short trajectories.
        - Test episodes are kept in full for long-horizon rollout evaluation.
      This lets you verify that the Hamiltonian structure generalises to horizons
      longer than seen during training (SRNN trains on T=9, tests on T=100).
      Manifest stores episode indices, train_frames, and num_steps so the data
      loader can enforce the frame cap on training clips exactly.
      Default ratio: 0.90.

Usage:
    python lehami/data/data_prep.py --dataset data/pendulum.h5
    python lehami/data/data_prep.py --dataset data/pendulum.h5 --split-method clip --num-steps 4 --frameskip 1
    python lehami/data/data_prep.py --dataset data/pendulum.h5 --seed 0 --train-ratio 0.75
    python lehami/data/data_prep.py --dataset data/pendulum.h5 --split-method episode_srnn --train-frames 10 --num-steps 10

Supported dataset types (auto-detected, or set with --dataset-type):
    pendulum  — 500 episodes; episode split is by episode index.
    pusht     — state-based Push-T generated by pusht_data.py (no pixels column).

Output:
    lehami/data/split_<stem>_<method>_seed<seed>.json          (episode / clip)
    lehami/data/split_<stem>_episode_srnn_K<K>_seed<seed>.json (episode_srnn)
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
from datetime import datetime, timezone
from pathlib import Path


# ── HDF5 inspection ───────────────────────────────────────────────────────────

def _inspect_hdf5(path: Path) -> dict:
    """Return basic metadata from an HDF5 file without loading pixel data."""
    import h5py
    with h5py.File(path, "r") as f:
        ep_len    = f["ep_len"][:]
        ep_offset = f["ep_offset"][:]
        state_shape  = f["state"].shape
        # State-only datasets (e.g. pusht_data.py) carry no `pixels` column.
        pixels_shape = f["pixels"].shape if "pixels" in f else None
        # Optional per-episode design columns (pendulum_multi.py).  When present
        # they let the split stratify by design cell and quarantine held-out
        # arms; absent, every split below falls back to a plain global shuffle.
        cell_keys = [k for k in ("length", "dt_mult", "mass_cell") if k in f]
        cells = ([tuple(v) for v in zip(*(f[k][:].tolist() for k in cell_keys))]
                 if cell_keys else None)
        held_out_dt = (sorted(int(v) for v in f.attrs["test_dt_mults"])
                       if "test_dt_mults" in f.attrs else [])
        dt_mult = f["dt_mult"][:].astype(int).tolist() if "dt_mult" in f else None
    out = {
        "n_episodes":  int(len(ep_len)),
        "n_frames":    int(pixels_shape[0] if pixels_shape else state_shape[0]),
        "frame_shape": list(pixels_shape[1:]) if pixels_shape else None,
        "state_dim":   int(state_shape[1]),
        "ep_len_min":  int(ep_len.min()),
        "ep_len_max":  int(ep_len.max()),
        "ep_len_mean": float(ep_len.mean()),
        "ep_offsets":  ep_offset.tolist(),
        "ep_lengths":  ep_len.tolist(),
    }
    if cells is not None:
        out["cell_keys"] = cell_keys
        out["ep_cells"]  = cells
    if dt_mult is not None:
        out["ep_dt_mult"]  = dt_mult
        out["held_out_dt"] = held_out_dt
    return out


def _partition_episodes(
    stats: dict,
    train_ratio: float,
    val_ratio: float,
    seed: int,
) -> tuple[list[int], list[int], list[int], list[int]]:
    """Assign whole episodes to train / val / test / ood.

    Three properties this has to guarantee, in order of how badly getting them
    wrong would hurt:

    1. **The held-out arm never reaches train or val.**  Episodes whose
       ``dt_mult`` is listed in the dataset's ``test_dt_mults`` attribute are
       pulled out first, into ``ood``.  Selecting a checkpoint on data drawn
       from the arm whose generalisation is the claim is the same class of
       test-set leak as the one fixed on 2026-08-09, one level up.
    2. **val is disjoint from test.**  They are different draws, so the
       checkpoint chosen on val is still scored on data it never saw.
    3. **Every split is balanced across design cells.**  Splitting globally
       would leave the (L, dt) composition of val to chance; with 15 cells and
       a 10% val share that is a real risk.  So the ratios are applied *within*
       each cell.

    Returns (train, val, test, ood), each a sorted list of episode indices.
    Datasets with no design columns get a plain global shuffle and an empty
    ``ood``, i.e. the pre-existing behaviour with val carved out of train.
    """
    n = stats["n_episodes"]
    if not 0.0 <= val_ratio < 1.0:
        raise ValueError(f"val_ratio must be in [0, 1), got {val_ratio}")
    if train_ratio + val_ratio > 1.0:
        raise ValueError(
            f"train_ratio + val_ratio = {train_ratio + val_ratio} > 1; "
            "no episodes would be left for test.")

    dt_mult  = stats.get("ep_dt_mult")
    held_out = set(stats.get("held_out_dt") or [])
    keep     = stats.get("restrict_dt_mults")     # None = keep every arm
    ood = sorted(i for i in range(n) if dt_mult and dt_mult[i] in held_out)
    pool = [i for i in range(n) if i not in set(ood)]
    if keep:
        # Drop non-selected arms entirely -- they appear in no split.  Used to
        # carve a single-dt slice out of the diversified file, which is the only
        # well-posed way to train a FIXED-step predictor on it: with several dt
        # in one training set and no dt input, "advance one frame" is ambiguous
        # (see paper/notes/temporal_encoder.tex, sec:te-multi).
        keep = set(int(k) for k in keep)
        pool = [i for i in pool if dt_mult[i] in keep]
        ood  = [i for i in ood if dt_mult[i] in keep]
        if not pool:
            raise ValueError(
                f"restrict_dt_mults={sorted(keep)} leaves no training episodes; "
                f"available arms are {sorted(set(dt_mult))}.")

    cells = stats.get("ep_cells")
    groups: dict = {}
    for i in pool:
        groups.setdefault(tuple(cells[i]) if cells else "_all", []).append(i)

    rng = random.Random(seed)
    train_idx, val_idx, test_idx = [], [], []
    for key in sorted(groups, key=repr):
        g = groups[key][:]
        rng.shuffle(g)
        n_tr = round(len(g) * train_ratio)
        n_va = round(len(g) * val_ratio)
        train_idx += g[:n_tr]
        val_idx   += g[n_tr:n_tr + n_va]
        test_idx  += g[n_tr + n_va:]
    return sorted(train_idx), sorted(val_idx), sorted(test_idx), ood


# ── dataset-type registry ─────────────────────────────────────────────────────

_AUTODETECT_KEYS = {
    frozenset(["ep_len", "ep_offset", "pixels", "state"]): "pendulum",
    frozenset(["ep_len", "ep_offset", "state", "action", "block_vel"]): "pusht",
}


def _detect_dataset_type(path: Path) -> str:
    import h5py
    with h5py.File(path, "r") as f:
        keys = frozenset(f.keys())
    for pattern, name in _AUTODETECT_KEYS.items():
        if pattern <= keys:
            return name
    raise ValueError(
        f"Cannot auto-detect dataset type for {path}. "
        f"Pass --dataset-type explicitly."
    )


# ── split methods ─────────────────────────────────────────────────────────────

def _split_report(stats: dict, seed: int, train_ratio: float, val_ratio: float,
                  train_idx: list[int], val_idx: list[int],
                  test_idx: list[int], ood_idx: list[int]) -> dict:
    """Shared manifest fields + the printout, for both episode split methods."""
    frames = lambda idx: sum(stats["ep_lengths"][i] for i in idx)  # noqa: E731
    print(f"Split   : {len(train_idx)} train / {len(val_idx)} val / {len(test_idx)} test"
          f" episodes  ({frames(train_idx)} / {frames(val_idx)} / {frames(test_idx)} frames,"
          f" train_ratio={train_ratio}, val_ratio={val_ratio}, seed={seed})")
    if ood_idx:
        print(f"Held out: {len(ood_idx)} episodes ({frames(ood_idx)} frames) at dt_mult "
              f"{stats.get('held_out_dt')} — quarantined from train AND val; "
              f"scored only as the unseen-dt test set.")
    info = {
        "train_ratio":           train_ratio,
        "val_ratio":             val_ratio,
        "seed":                  seed,
        "n_total_episodes":      stats["n_episodes"],
        "n_train_episodes":      len(train_idx),
        "n_val_episodes":        len(val_idx),
        "n_test_episodes":       len(test_idx),
        "n_train_frames":        frames(train_idx),
        "n_val_frames":          frames(val_idx),
        "n_test_frames":         frames(test_idx),
        "train_episode_indices": train_idx,
        "val_episode_indices":   val_idx,
        "test_episode_indices":  test_idx,
    }
    if ood_idx:
        info.update({
            "held_out_dt":         stats.get("held_out_dt"),
            "n_ood_episodes":      len(ood_idx),
            "n_ood_frames":        frames(ood_idx),
            "ood_episode_indices": ood_idx,
        })
    return info


def _split_episode(
    stats: dict,
    train_ratio: float,
    seed: int,
    val_ratio: float = 0.0,
) -> dict:
    """Assign whole episodes to train / val / test (and quarantine held-out dt)."""
    train_idx, val_idx, test_idx, ood_idx = _partition_episodes(
        stats, train_ratio, val_ratio, seed)
    return {
        "split_method": "episode",
        **_split_report(stats, seed, train_ratio, val_ratio,
                        train_idx, val_idx, test_idx, ood_idx),
    }


def _split_episode_srnn(
    stats: dict,
    train_ratio: float,
    seed: int,
    train_frames: int,
    num_steps: int,
    clip_stride: int = 1,
    val_ratio: float = 0.0,
) -> dict:
    """Episode-level split with truncated training trajectories (SRNN protocol).

    Training episodes expose only their first `train_frames` frames, yielding
    clips of length `num_steps` via a sliding window advanced by `clip_stride`:
        clips per train episode = len(range(0, train_frames - num_steps + 1, clip_stride))
    Test episodes are kept in full for long-horizon rollout evaluation.

    Args:
        train_frames: Number of frames to use from the start of each training
                      episode (analogous to T=9 in the SRNN paper).
        num_steps:    Clip length (frames per training example); must be
                      <= train_frames.  Enforced at training time: train.py
                      errors if cfg.history_size + cfg.num_preds differs.
        clip_stride:  Step between consecutive clip start positions (default 1
                      = every start position, maximally overlapping windows).
    """
    if num_steps > train_frames:
        raise ValueError(
            f"num_steps ({num_steps}) must be <= train_frames ({train_frames})"
        )
    if clip_stride < 1:
        raise ValueError(f"clip_stride must be >= 1, got {clip_stride}")

    train_idx, val_idx, test_idx, ood_idx = _partition_episodes(
        stats, train_ratio, val_ratio, seed)

    # Train/val are frame-capped (the SRNN budget); test and ood are kept in
    # full for long-horizon rollout.
    n_train_frames = sum(min(stats["ep_lengths"][i], train_frames) for i in train_idx)
    clips_per_ep = len(range(0, train_frames - num_steps + 1, clip_stride))

    info = _split_report(stats, seed, train_ratio, val_ratio,
                         train_idx, val_idx, test_idx, ood_idx)
    info["n_train_frames"] = n_train_frames   # capped, not the full-episode sum
    print(
        f"Train   : first {train_frames} frames per episode  ({n_train_frames} frames total)"
    )
    print(
        f"Clips   : {num_steps} frames, stride {clip_stride}"
        f"  → {clips_per_ep} clips/episode, {clips_per_ep * len(train_idx)} total"
    )
    print(f"Test    : full episodes  ({info['n_test_frames']} frames total)")

    return {
        "split_method": "episode_srnn",
        "train_frames": train_frames,
        "num_steps":    num_steps,
        "clip_stride":  clip_stride,
        **info,
    }


def _split_clip(
    stats: dict,
    train_ratio: float,
    seed: int,
    num_steps: int,
    frameskip: int,
) -> dict:
    """Record the parameters that reproduce the clip-level split used by train.py.

    HDF5Dataset slides a window of `num_steps` frames (with `frameskip`) over
    every episode.  The resulting clip list is shuffled and divided by
    spt.data.random_split using the given seed and ratio.  We compute the
    expected clip counts here from episode lengths so the manifest is
    informative without having to instantiate the full dataset.
    """
    step = frameskip  # frames advanced per clip step
    # clips per episode = max(0, ep_len - (num_steps - 1) * step - 1 + 1)
    #                   = max(0, ep_len - (num_steps - 1) * step)
    ep_clips = [
        max(0, L - (num_steps - 1) * step)
        for L in stats["ep_lengths"]
    ]
    n_total_clips = sum(ep_clips)
    n_train_clips = round(n_total_clips * train_ratio)
    n_test_clips  = n_total_clips - n_train_clips

    print(f"Split   : {n_train_clips} train clips / {n_test_clips} test clips"
          f"  (total={n_total_clips}, num_steps={num_steps}, frameskip={frameskip},"
          f" ratio={train_ratio}, seed={seed})")
    print("          Reproduce with: spt.data.random_split(dataset,"
          f" [{train_ratio}, {1-train_ratio}], generator=torch.Generator().manual_seed({seed}))")

    return {
        "split_method":    "clip",
        "train_ratio":     train_ratio,
        "seed":            seed,
        "num_steps":       num_steps,
        "frameskip":       frameskip,
        "n_total_clips":   n_total_clips,
        "n_train_clips":   n_train_clips,
        "n_test_clips":    n_test_clips,
    }


# ── utilities ─────────────────────────────────────────────────────────────────

def _file_sha256(path: Path, chunk: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            block = f.read(chunk)
            if not block:
                break
            h.update(block)
    return h.hexdigest()


# ── public API ────────────────────────────────────────────────────────────────

def prepare(
    dataset_path: Path,
    dataset_type: str | None = None,
    split_method: str = "episode",
    train_ratio: float | None = None,
    seed: int = 42,
    out_dir: Path | None = None,
    val_ratio: float = 0.0,
    restrict_dt_mults: list[int] | None = None,
    # clip / episode_srnn parameters
    num_steps: int = 4,
    frameskip: int = 1,
    # episode_srnn-only parameters
    train_frames: int = 10,
    clip_stride: int = 1,
) -> Path:
    """Run data prep and write the split manifest; return the manifest path.

    Args:
        dataset_path:  Path to the .h5 file.
        dataset_type:  Dataset type string; auto-detected when None.
        split_method:  "episode", "clip", or "episode_srnn".
        train_ratio:   Fraction for training.  Defaults to 0.75 for "episode",
                       0.90 for "clip" and "episode_srnn".
        seed:          RNG seed.
        out_dir:       Directory for the manifest JSON.  Defaults to the same
                       folder as this script.
        num_steps:     Frames per clip (clip and episode_srnn methods).
        frameskip:     Frame stride (clip method only).
        train_frames:  First K frames used per training episode (episode_srnn
                       only; analogous to T=9 in the SRNN paper).
        clip_stride:   Step between clip start positions within the frame
                       budget (episode_srnn only; default 1 = every position).
    """
    _VALID_METHODS = ("episode", "clip", "episode_srnn")
    if split_method not in _VALID_METHODS:
        raise ValueError(f"split_method must be one of {_VALID_METHODS}, got {split_method!r}")
    if train_ratio is None:
        train_ratio = 0.75 if split_method == "episode" else 0.90

    dataset_path = dataset_path.resolve()
    if dataset_type is None:
        dataset_type = _detect_dataset_type(dataset_path)

    print(f"Dataset : {dataset_path}")
    print(f"Type    : {dataset_type}  |  Method: {split_method}")

    stats = _inspect_hdf5(dataset_path)
    if restrict_dt_mults:
        stats["restrict_dt_mults"] = [int(k) for k in restrict_dt_mults]
        print(f"Restrict: keeping only dt_mult {stats['restrict_dt_mults']} "
              f"(other arms appear in NO split)")
    print(f"Episodes: {stats['n_episodes']}  |  Frames: {stats['n_frames']}"
          f"  |  State dim: {stats['state_dim']}")

    if split_method == "episode":
        split_info = _split_episode(stats, train_ratio, seed, val_ratio)
    elif split_method == "episode_srnn":
        split_info = _split_episode_srnn(stats, train_ratio, seed, train_frames,
                                         num_steps, clip_stride, val_ratio)
    else:
        if val_ratio:
            raise ValueError(
                "val_ratio is only supported for the episode / episode_srnn split "
                "methods; a clip-level val split would share episodes with train.")
        split_info = _split_clip(stats, train_ratio, seed, num_steps, frameskip)

    manifest = {
        "created_at":     datetime.now(timezone.utc).isoformat(),
        "dataset_path":   str(dataset_path),
        "dataset_sha256": _file_sha256(dataset_path),
        "dataset_type":   dataset_type,
        **split_info,
        "dataset_stats":  stats,
    }

    out_dir = (out_dir or Path(__file__).parent).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    # `_val` in the name so a three-way manifest can never be confused with a
    # two-way one at a glance — they select checkpoints differently.
    vtag = f"_val{val_ratio:g}".replace("0.", ".") if val_ratio else ""
    if restrict_dt_mults:
        vtag += "_dt" + "".join(str(int(k)) for k in sorted(restrict_dt_mults))
    if split_method == "episode_srnn":
        filename = (f"split_{dataset_path.stem}_episode_srnn_K{train_frames}"
                    f"{vtag}_seed{seed}.json")
    else:
        filename = f"split_{dataset_path.stem}_{split_method}{vtag}_seed{seed}.json"
    out_path = out_dir / filename
    out_path.write_text(json.dumps(manifest, indent=2))
    print(f"Manifest: {out_path}")
    return out_path


# ── CLI ───────────────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--dataset",      required=True, type=Path,
                        help="Path to the .h5 dataset file")
    parser.add_argument("--dataset-type", default=None,
                        help="Dataset type (default: auto-detect)")
    parser.add_argument("--split-method", default="episode",
                        choices=["episode", "clip", "episode_srnn"],
                        help="'episode': whole-episode split (default); "
                             "'clip': clip-level split matching train.py; "
                             "'episode_srnn': episode split + truncated training trajectories")
    parser.add_argument("--train-ratio",  default=None, type=float,
                        help="Training fraction (default: 0.75 for episode, 0.90 for clip)")
    parser.add_argument("--val-ratio",    default=0.0, type=float,
                        help="Validation fraction, carved out of the non-held-out "
                             "episodes alongside train/test (episode and episode_srnn "
                             "only, default: 0.0 = no val split). Use this so "
                             "checkpoints are selected on data that is neither trained "
                             "on nor reported.")
    parser.add_argument("--restrict-dt-mults", default=None, type=int, nargs="+",
                        help="Keep only these dt multipliers; all other arms are dropped "
                             "from every split. Use to carve a single-dt slice out of the "
                             "diversified file for a fixed-step predictor.")
    parser.add_argument("--seed",         default=42, type=int,
                        help="Random seed (default: 42)")
    parser.add_argument("--out-dir",      default=None, type=Path,
                        help="Output directory for the manifest (default: folder of this script)")
    # clip / episode_srnn
    parser.add_argument("--num-steps",     default=4, type=int,
                        help="Frames per clip (clip and episode_srnn methods, default: 4)")
    parser.add_argument("--frameskip",     default=1, type=int,
                        help="Frame stride (clip method only, default: 1)")
    # episode_srnn-only
    parser.add_argument("--train-frames",  default=10, type=int,
                        help="First K frames per training episode (episode_srnn only, default: 10; "
                             "analogous to T=9 in the SRNN paper)")
    parser.add_argument("--clip-stride",   default=1, type=int,
                        help="Step between clip start positions (episode_srnn only, default: 1 "
                             "= every start position, maximally overlapping windows)")
    args = parser.parse_args()

    prepare(
        dataset_path=args.dataset,
        dataset_type=args.dataset_type,
        split_method=args.split_method,
        train_ratio=args.train_ratio,
        seed=args.seed,
        out_dir=args.out_dir,
        val_ratio=args.val_ratio,
        restrict_dt_mults=args.restrict_dt_mults,
        num_steps=args.num_steps,
        frameskip=args.frameskip,
        train_frames=args.train_frames,
        clip_stride=args.clip_stride,
    )


if __name__ == "__main__":
    main()
